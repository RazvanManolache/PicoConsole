from pathlib import Path
import json,re,shutil
root=Path(__file__).resolve().parents[1];src=root/'upstream/gamebuino-sdl/src/gameworld';dst=root/'firmware/gamebuino'
games=json.loads((root/'tools/gamebuino-games.json').read_text())
def put(p,s):
 p.parent.mkdir(parents=True,exist_ok=True)
 if not p.exists() or p.read_text(encoding='utf-8')!=s:p.write_text(s,encoding='utf-8')
def adapt(s):return '// PicoConsole backend/flash modifications, 2026-10-11; original notices retained.\n'+re.sub(r'\bmd_','gb_md_',re.sub(r'\beeprom(?=_|SelectGame\b)','gb_eeprom',s))
for name in ('avrCompat.h','machineDependent.h','gamebuinoShim.h','gamebuinoShim.c','eepromShim.h'):
 s=(src/name).read_text(encoding='utf-8')
 if name.startswith('gamebuinoShim'):
  s='// Gamebuino API and fonts: Copyright 2014 Aurelien Rodot, LGPL-3.0-or-later.\n// C port modifications: joyrider3774, GPLv3; full notices in LICENSES.\n'+s
 s=re.sub(r'\bint (gbFont(?:5x7|3x5|3x3))\[',r'const int \1[',s)
 put(dst/'core'/name,adapt(s))
for g in games:
 s=(src/'games'/g['folder']).read_text(encoding='utf-8');s=re.sub(r'^#include "([^"]+)"',r'#include "../core/\1"',s,flags=re.M)
 assert not re.search(r'non[- ]commercial|CC[- ]BY[- ]NC|NoDerivs',s,re.I),g['id']
 def table(m):
  n=m[3];post=s[s.index('};',m.end())+2:]
  writes=re.search(r'\b'+n+r'\s*\[[^\]\n]*\](?:\s*\[[^\]\n]*\])*\s*(?:[+*/%&|^-]?=(?!=)|\+\+|--)',post)
  dest=re.search(r'\bmem(?:cpy|set)\s*\(\s*'+n+r'\b',post)
  return m[0] if writes or dest else (m[1] or '')+'const '+m[2]+n+m[4]
 s=re.sub(r'^(static\s+)?(int\s+)(\w+)(\s*\[[^;=]*=\s*\{)',table,s,flags=re.M)
 if g['function']=='gameBRally':
  # Index-only immutable track values are -7..7, not 32-bit quantities.
  for name,values in re.findall(r'const int (brallyTrack\w+)\[10000\] = \{(.*?)\};',s,re.S):
   nums=list(map(int,re.findall(r'-?\d+',values)))
   assert len(nums)==10000 and all(-128<=v<=127 for v in nums)
   s=s.replace('const int '+name+'[','const signed char '+name+'[')
 if g['function']=='gameBub':
  # Levels are copied into the separate mutable bubLvlData grid.
  s=s.replace('char bubLevels[6401]','const char bubLevels[6401]')
 put(dst/'games'/g['folder'],adapt(s))
decl=[];entries=[];wrappers=[]
for i,g in enumerate(games):
 n=g['function'];decl.append(f'void {n}_init(void);void {n}_update(void);');entries.append('{'+n+'_init,'+n+'_update,'+json.dumps(g['title'])+'}')
 wrappers.append('namespace '+g['id']+' { void run() { gamebuino_run('+str(i)+'); } }')
layouts=','.join('1' if g['function']=='gameTetrino' else '0' for g in games)
put(dst/'selection.c','// Generated by PicoConsole; GPL-3.0-only.\n#include "runtime.h"\ntypedef struct {void (*init)(void);void (*update)(void);const char* title;} Entry;\n'+'\n'.join(decl)+'\nstatic const Entry selected[]={\n'+',\n'.join(entries)+'\n};\nstatic const int layouts[]={'+layouts+'};\nstatic int active;\nvoid gamebuino_select(int i){active=i;gamebuino_reset();gamebuino_set_layout(layouts[i]);selected[i].init();}\nvoid gamebuino_update(void){selected[active].update();}\nint gamebuino_game_count(void){return sizeof(selected)/sizeof(selected[0]);}\nconst char* gamebuino_game_title(int i){return selected[i].title;}\n')
put(dst/'entries.inc','\n'.join(wrappers)+'\n')
put(dst/'sources.cmake','set(GAMEBUINO_SOURCES\n  gamebuino/core/gamebuinoShim.c\n'+''.join('  gamebuino/games/'+g['folder']+'\n' for g in games)+')\n')
shutil.copyfile(root/'upstream/gamebuino-sdl/LICENSE.txt',dst/'LICENSE.txt')
p=root/'tools/native_catalog.json';catalog=[g for g in json.loads(p.read_text()) if g['group']!='GAMEBUINO'];catalog.extend(games);p.write_text(json.dumps(catalog,indent=2)+'\n')
print('Prepared',len(games),'Gamebuino games.')
