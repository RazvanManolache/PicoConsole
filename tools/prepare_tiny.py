from pathlib import Path
import json,re,shutil
root=Path(__file__).resolve().parents[1]
src=root/'upstream/tinyjoypad-sdl/src/gameworld';dst=root/'firmware/tiny'
games=json.loads((root/'tools/tiny-games.json').read_text())
def put(path,text):
 path.parent.mkdir(parents=True,exist_ok=True)
 if not path.exists() or path.read_text(encoding='utf-8')!=text:path.write_text(text,encoding='utf-8')
def adapt(text):
 # Keep this backend's C ABI separate from Crisp's md_* entry points.
 return '// PicoConsole backend/flash modifications, 2026-10-11; upstream notices retained.\n'+re.sub(r'\bmd_', 'tj_md_',text)
for name in ('avrCompat.h','machineDependent.h','tinyJoypadShim.h','tinyJoypadShim.c','obonoCoreShim.h','obonoCoreShim.c','menu.h','eepromShim.h'):
 text=(src/name).read_text(encoding='utf-8')
 if name=='obonoCoreShim.c':
  text=text.replace('int imgFont[','const int imgFont[').replace('int noteFrequency[','const int noteFrequency[')
  text+='\nvoid tinyCoreReset(void) { initCore(); buttonState=lastButtonState=justPressedState=0; scorePos=-1; playingScore=NULL; scoreStopAtFrame=-1; clearScreenBuffer(); }\n'
 put(dst/'core'/name,adapt(text))
for g in games:
 text=(src/'games'/g['folder']).read_text(encoding='utf-8')
 text=re.sub(r'#include "([^"]+)"',r'#include "../core/\1"',text)
 assert not re.search(r'non[- ]commercial|CC[- ]BY[- ]NC|NoDerivs',text,re.I),g['id']
 # All initialized file-scope int arrays in these selected files are lookup,
 # graphics, puzzle or sound tables. Mutable play state uses separate BSS.
 # Keeping them in flash avoids copying several hundred KB into SRAM.
 text=re.sub(r'^(static\s+)?(int\s+\w+\s*\[[^;=]*=\s*\{)',lambda m:(m[1] or '')+'const '+m[2],text,flags=re.M)
 put(dst/'games'/g['folder'],adapt(text))
decl=[];entries=[];wrappers=[]
for i,g in enumerate(games):
 name=g['function'];decl.append(f'void {name}_init(void); void {name}_update(void);')
 entries.append('{'+json.dumps(g['title'])+', '+json.dumps(g['author'])+', '+name+'_init, '+name+'_update, 0}')
 wrappers.append('namespace '+g['id']+' { void run() { tiny_run('+str(i)+'); } }')
layouts=[1 if g['function']=='gameAttinyTetromino' else 2 if g['function']=='gameNumberPlace' else 0 for g in games]
put(dst/'selection.c','// Generated by PicoConsole; GPL-3.0-only.\n#include "runtime.h"\n#include "core/menu.h"\n'+ '\n'.join(decl)+'\nstatic const Game selected[]={\n'+',\n'.join(entries)+'\n};\nstatic const int layouts[]={'+','.join(map(str,layouts))+'};\nstatic int active;\nvoid tiny_select(int i) { active=i; tiny_reset(); tiny_set_layout(layouts[i]); selected[i].init(); }\nvoid tiny_update(void) { selected[active].update(); }\nint tiny_game_count(void) { return sizeof(selected)/sizeof(selected[0]); }\nconst char* tiny_game_title(int i) { return selected[i].title; }\n')
put(dst/'entries.inc','\n'.join(wrappers)+'\n')
put(dst/'sources.cmake','set(TINY_SOURCES\n  tiny/core/tinyJoypadShim.c\n  tiny/core/obonoCoreShim.c\n'+''.join('  tiny/games/'+g['folder']+'\n' for g in games)+')\n')
shutil.copyfile(root/'upstream/tinyjoypad-sdl/LICENSE.txt',dst/'LICENSE.txt')
p=root/'tools/native_catalog.json';catalog=[g for g in json.loads(p.read_text()) if g['group']!='TINYEXTRA'];catalog.extend(games)
p.write_text(json.dumps(catalog,indent=2)+'\n')
print(f'Prepared {len(games)} additional TinyJoypad games; readonly tables in flash.')
